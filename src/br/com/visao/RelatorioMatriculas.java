    private void jBgerarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBgerarActionPerformed
        // TODO add your handling code here:
        LocalDate inicio = null;
        LocalDate fim = null;
        try {
            if (!jTinicio.getText().trim().equals("")) {
                inicio = LocalDate.parse(jTinicio.getText().trim(), formato);
            }
            if (!jTfim.getText().trim().equals("")) {
                fim = LocalDate.parse(jTfim.getText().trim(), formato);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Data inválida! Use o formato dd/mm/aaaa");
            return;
        }
        try {
            ControleRelatorio cr = new ControleRelatorio();
            ItemCombo unidade = (ItemCombo) jCbunidade.getSelectedItem();
            String status = jCbstatus.getSelectedItem().toString();
            ArrayList<MatriculaDetalhada> lista = cr.gerarRelatorio(inicio, fim, unidade.getId(), status);

            DefaultTableModel modelo = (DefaultTableModel) jTbrelatorio.getModel();
            modelo.setRowCount(0);
            for (int i = 0; i < lista.size(); i++) {
                MatriculaDetalhada md = lista.get(i);
                String termino = "";
                if (md.getDataTermino() != null) {
                    termino = md.getDataTermino().format(formato);
                }
                modelo.addRow(new Object[]{md.getMatriculaId(), md.getNomeAluno(), md.getNomePlano(), md.getNomeUnidade(), md.getDataInicio().format(formato), termino, md.getStatus(), md.getValor().toString().replace(".", ",")});
            }
            // totais embaixo da tabela
            BigDecimal soma = cr.somarValores(lista);
            jLtotal.setText("Total de matrículas: " + lista.size());
            jLsoma.setText("Soma dos valores: R$ " + soma.toString().replace(".", ","));
            if (lista.size() == 0) {
                JOptionPane.showMessageDialog(this, "Nenhuma matrícula nesse período!");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_jBgerarActionPerformed

