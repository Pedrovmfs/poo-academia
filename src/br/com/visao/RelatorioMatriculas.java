    // enche a caixa de unidades; codigo 0 = todas as unidades
    private void carregarUnidades() {
        try {
            ControleRelatorio cr = new ControleRelatorio();
            ArrayList<ItemCombo> unidades = cr.listarUnidades();
            jCbunidade.removeAllItems();
            jCbunidade.addItem(new ItemCombo(0, "Todas"));
            for (int i = 0; i < unidades.size(); i++) {
                jCbunidade.addItem(unidades.get(i));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar as unidades: " + e.getMessage());
        }
    }

