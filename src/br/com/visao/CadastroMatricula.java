    private void jTbmatriculaMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTbmatriculaMouseClicked
        // TODO add your handling code here:
        // a tabela so tem os nomes, entao busca a matricula completa pelo codigo
        int linha = jTbmatricula.getSelectedRow();
        if (linha >= 0) {
            try {
                Matricula m = new Matricula();
                ControleMatricula cm = new ControleMatricula();
                m.setMatriculaId(Integer.valueOf(jTbmatricula.getValueAt(linha, 0).toString()));
                cm.buscar(m);
                jTcodigo.setText(String.valueOf(m.getMatriculaId()));
                selecionar(jCbaluno, m.getAlunoId());
                selecionar(jCbplano, m.getPlanoId());
                selecionar(jCbunidade, m.getUnidadeId());
                jTinicio.setText(m.getDataInicio().format(formato));
                if (m.getDataTermino() != null) {
                    jTtermino.setText(m.getDataTermino().format(formato));
                } else {
                    jTtermino.setText("");
                }
                jCbstatus.setSelectedItem(m.getStatus());
                jCbrenovacao.setSelectedItem(m.getFormaRenovacao());
                jCbcanal.setSelectedItem(m.getCanalMatricula());
                if (m.getMotivoCancelamento() != null) {
                    jTmotivo.setText(m.getMotivoCancelamento());
                } else {
                    jTmotivo.setText("");
                }
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_jTbmatriculaMouseClicked

    // enche as caixas de aluno, plano e unidade com o que tem no banco
    private void carregarCombos() {
        try {
            ControleMatricula cm = new ControleMatricula();
            ArrayList<ItemCombo> alunos = cm.listarAlunos();
            ArrayList<ItemCombo> planos = cm.listarPlanos();
            ArrayList<ItemCombo> unidades = cm.listarUnidades();
            jCbaluno.removeAllItems();
            jCbplano.removeAllItems();
            jCbunidade.removeAllItems();
            // primeiro item com codigo 0 = nada escolhido ainda
            jCbaluno.addItem(new ItemCombo(0, "Selecione..."));
            jCbplano.addItem(new ItemCombo(0, "Selecione..."));
            jCbunidade.addItem(new ItemCombo(0, "Selecione..."));
            for (int i = 0; i < alunos.size(); i++) {
                jCbaluno.addItem(alunos.get(i));
            }
            for (int i = 0; i < planos.size(); i++) {
                jCbplano.addItem(planos.get(i));
            }
            for (int i = 0; i < unidades.size(); i++) {
                jCbunidade.addItem(unidades.get(i));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao carregar as listas: " + e.getMessage());
        }
    }

    // escolhe na caixa o item que tem o codigo informado
    private void selecionar(JComboBox<ItemCombo> combo, int id) {
        for (int i = 0; i < combo.getItemCount(); i++) {
            if (combo.getItemAt(i).getId() == id) {
                combo.setSelectedIndex(i); // Achou o item com o mesmo codigo, entao seleciona ele
            }
        }
    }

    private void carregarTabela() {
        try {
            ControleMatricula cm = new ControleMatricula();
            DefaultTableModel modelo = (DefaultTableModel) jTbmatricula.getModel();
            modelo.setRowCount(0); // Zera as linhas, senao duplica tudo
            ArrayList<Matricula> matriculas = cm.listar();
            for (int i = 0; i < matriculas.size(); i++) {
                Matricula m = matriculas.get(i);
                String termino = "";
                if (m.getDataTermino() != null) {
                    termino = m.getDataTermino().format(formato);
                }
                modelo.addRow(new Object[]{m.getMatriculaId(), m.getNomeAluno(), m.getNomePlano(), m.getNomeUnidade(), m.getDataInicio().format(formato), termino, m.getStatus()});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao listar: " + e.getMessage());
        }
    }

    private void limpar() {
        jTcodigo.setText("");
        jCbaluno.setSelectedIndex(0);
        jCbplano.setSelectedIndex(0);
        jCbunidade.setSelectedIndex(0);
        jTinicio.setText("");
        jTtermino.setText("");
        jCbstatus.setSelectedIndex(0);
        jCbrenovacao.setSelectedIndex(0);
        jCbcanal.setSelectedIndex(0);
        jTmotivo.setText("");
        jTbmatricula.clearSelection();
    }

