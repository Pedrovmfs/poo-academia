    private void jBsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBsalvarActionPerformed
        // TODO add your handling code here:
        try {
            Matricula m = new Matricula();
            ControleMatricula cm = new ControleMatricula();
            // o item escolhido guarda o codigo, a tela so mostra o nome
            ItemCombo aluno = (ItemCombo) jCbaluno.getSelectedItem(); // Cast porque o getSelectedItem devolve Object
            ItemCombo plano = (ItemCombo) jCbplano.getSelectedItem();
            ItemCombo unidade = (ItemCombo) jCbunidade.getSelectedItem();
            m.setAlunoId(aluno.getId());
            m.setPlanoId(plano.getId());
            m.setUnidadeId(unidade.getId());
            if (!jTinicio.getText().trim().equals("")) {
                try {
                    m.setDataInicio(LocalDate.parse(jTinicio.getText().trim(), formato));
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Data inválida! Use o formato dd/mm/aaaa");
                    return;
                }
            }
            m.setStatus(jCbstatus.getSelectedItem().toString());
            m.setFormaRenovacao(jCbrenovacao.getSelectedItem().toString());
            m.setCanalMatricula(jCbcanal.getSelectedItem().toString());
            if (!jTmotivo.getText().trim().equals("")) {
                m.setMotivoCancelamento(jTmotivo.getText().trim());
            }

            // mesmo esquema das outras telas: sem codigo cadastra, com codigo altera
            if (jTcodigo.getText().equals("")) {
                cm.inserir(m);
                JOptionPane.showMessageDialog(this, "Matrícula cadastrada com sucesso! Término: " + m.getDataTermino().format(formato));
            } else {
                m.setMatriculaId(Integer.valueOf(jTcodigo.getText()));
                cm.alterar(m);
                JOptionPane.showMessageDialog(this, "Matrícula alterada com sucesso! Término: " + m.getDataTermino().format(formato));
            }
            limpar();
            carregarTabela();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_jBsalvarActionPerformed

    private void jBexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBexcluirActionPerformed
        // TODO add your handling code here:
        if (jTcodigo.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Selecione uma matrícula na tabela!");
            return;
        }
        int resposta = JOptionPane.showConfirmDialog(this, "Deseja excluir esta matrícula?", "Excluir", JOptionPane.YES_NO_OPTION);
        if (resposta == JOptionPane.YES_OPTION) {
            try {
                Matricula m = new Matricula();
                ControleMatricula cm = new ControleMatricula();
                m.setMatriculaId(Integer.valueOf(jTcodigo.getText()));
                cm.deletar(m);
                JOptionPane.showMessageDialog(this, "Matrícula excluída com sucesso!");
                limpar();
                carregarTabela();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_jBexcluirActionPerformed

