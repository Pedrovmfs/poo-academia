    // mostra as matriculas com os nomes (vindos do INNER JOIN), filtrando pelo nome do aluno
    private void carregarTabela(String nome) {
        try {
            ControleRelatorio cr = new ControleRelatorio();
            DefaultTableModel modelo = (DefaultTableModel) jTbconsulta.getModel();
            modelo.setRowCount(0);
            ArrayList<MatriculaDetalhada> lista = cr.consultar(nome);
            for (int i = 0; i < lista.size(); i++) {
                MatriculaDetalhada md = lista.get(i);
                String termino = "";
                if (md.getDataTermino() != null) {
                    termino = md.getDataTermino().format(formato);
                }
                modelo.addRow(new Object[]{md.getMatriculaId(), md.getNomeAluno(), md.getNomePlano(), md.getNomeUnidade(), md.getDataInicio().format(formato), termino, md.getStatus(), md.getValor().toString().replace(".", ",")});
            }
            if (lista.size() == 0) {
                JOptionPane.showMessageDialog(this, "Nenhuma matrícula encontrada!");
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao consultar: " + e.getMessage());
        }
    }

