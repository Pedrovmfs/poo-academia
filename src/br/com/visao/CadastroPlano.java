    private void jTbplanoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTbplanoMouseClicked
        // TODO add your handling code here:
        // clicou na tabela, preenche o formulario
        int linha = jTbplano.getSelectedRow();
        if (linha >= 0) {
            jTcodigo.setText(jTbplano.getValueAt(linha, 0).toString());
            jTnome.setText(jTbplano.getValueAt(linha, 1).toString());
            jTvalor.setText(jTbplano.getValueAt(linha, 2).toString());
            jTduracao.setText(jTbplano.getValueAt(linha, 3).toString());
            jCmultiunidade.setSelected(jTbplano.getValueAt(linha, 4).toString().equals("Sim"));
        }
    }//GEN-LAST:event_jTbplanoMouseClicked

    private void carregarTabela() {
        try {
            ControlePlano cp = new ControlePlano();
            DefaultTableModel modelo = (DefaultTableModel) jTbplano.getModel();
            modelo.setRowCount(0);
            ArrayList<Plano> planos = cp.listar();
            for (int i = 0; i < planos.size(); i++) {
                Plano p = planos.get(i);
                String multi = "Não";
                if (p.isAcessoMultiunidade()) {
                    multi = "Sim";
                }
                modelo.addRow(new Object[]{p.getPlanoId(), p.getNome(), p.getValor().toString().replace(".", ","), p.getDuracaoMeses(), multi});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao listar: " + e.getMessage());
        }
    }

    private void limpar() {
        jTcodigo.setText("");
        jTnome.setText("");
        jTvalor.setText("");
        jTduracao.setText("");
        jCmultiunidade.setSelected(false);
        jTbplano.clearSelection();
    }

