    private void jBsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBsalvarActionPerformed
        // TODO add your handling code here:
        try {
            Plano p = new Plano();
            ControlePlano cp = new ControlePlano();
            p.setNome(jTnome.getText().trim());
            if (!jTvalor.getText().trim().equals("")) {
                try {
                    p.setValor(new BigDecimal(jTvalor.getText().trim().replace(",", ".")));
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Valor inválido! Exemplo: 119,90");
                    return;
                }
            }
            if (!jTduracao.getText().trim().equals("")) {
                try {
                    p.setDuracaoMeses(Integer.valueOf(jTduracao.getText().trim()));
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Duração inválida! Digite só o número de meses");
                    return;
                }
            }
            p.setAcessoMultiunidade(jCmultiunidade.isSelected());

            // se o codigo ta vazio é cadastro novo, senao altera
            if (jTcodigo.getText().equals("")) {
                cp.inserir(p);
                JOptionPane.showMessageDialog(this, "Plano cadastrado com sucesso!");
            } else {
                p.setPlanoId(Integer.valueOf(jTcodigo.getText()));
                cp.alterar(p);
                JOptionPane.showMessageDialog(this, "Plano alterado com sucesso!");
            }
            limpar();
            carregarTabela();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_jBsalvarActionPerformed

    private void jBexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBexcluirActionPerformed
        // TODO add your handling code here:
        if (jTcodigo.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Selecione um plano na tabela!");
            return;
        }
        int resposta = JOptionPane.showConfirmDialog(this, "Deseja excluir este plano?", "Excluir", JOptionPane.YES_NO_OPTION);
        if (resposta == JOptionPane.YES_OPTION) {
            try {
                Plano p = new Plano();
                ControlePlano cp = new ControlePlano();
                p.setPlanoId(Integer.valueOf(jTcodigo.getText()));
                cp.deletar(p);
                JOptionPane.showMessageDialog(this, "Plano excluído com sucesso!");
                limpar();
                carregarTabela();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_jBexcluirActionPerformed

