    private void jBsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBsalvarActionPerformed
        // TODO add your handling code here:
        try {
            Unidade u = new Unidade();
            ControleUnidade cu = new ControleUnidade();
            u.setNome(jTnome.getText().trim());
            u.setEndereco(jTendereco.getText().trim());
            if (!jTtelefone.getText().trim().equals("")) {
                u.setTelefone(jTtelefone.getText().trim());
            }
            if (!jThorario.getText().trim().equals("")) {
                u.setHorarioFuncionamento(jThorario.getText().trim());
            }
            if (!jTdata.getText().trim().equals("")) {
                try {
                    u.setDataInauguracao(LocalDate.parse(jTdata.getText().trim(), formato));
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Data inválida! Use o formato dd/mm/aaaa");
                    return;
                }
            }
            if (!jTcusto.getText().trim().equals("")) {
                try {
                    u.setCustoMensalOcupacao(new BigDecimal(jTcusto.getText().trim().replace(",", "."))); // Troca a virgula por ponto, pois o BigDecimal so entende ponto
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Custo mensal inválido! Exemplo: 1500,00");
                    return;
                }
            }

            // Sem codigo = unidade nova, com codigo = alterar
            if (jTcodigo.getText().equals("")) {
                cu.inserir(u);
                JOptionPane.showMessageDialog(this, "Unidade cadastrada com sucesso!");
            } else {
                u.setUnidadeId(Integer.valueOf(jTcodigo.getText())); // O campo é texto, entao converte pra int
                cu.alterar(u);
                JOptionPane.showMessageDialog(this, "Unidade alterada com sucesso!");
            }
            limpar();
            carregarTabela();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_jBsalvarActionPerformed

    private void jBexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBexcluirActionPerformed
        // TODO add your handling code here:
        if (jTcodigo.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Selecione uma unidade na tabela!");
            return;
        }
        int resposta = JOptionPane.showConfirmDialog(this, "Deseja excluir esta unidade?", "Excluir", JOptionPane.YES_NO_OPTION);
        if (resposta == JOptionPane.YES_OPTION) {
            try {
                Unidade u = new Unidade();
                ControleUnidade cu = new ControleUnidade();
                u.setUnidadeId(Integer.valueOf(jTcodigo.getText()));
                cu.deletar(u);
                JOptionPane.showMessageDialog(this, "Unidade excluída com sucesso!");
                limpar();
                carregarTabela();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_jBexcluirActionPerformed

