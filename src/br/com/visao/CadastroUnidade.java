    private void jTbunidadeMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTbunidadeMouseClicked
        // TODO add your handling code here:
        // Pega a linha clicada e joga nos campos
        int linha = jTbunidade.getSelectedRow();
        if (linha >= 0) {
            jTcodigo.setText(texto(jTbunidade.getValueAt(linha, 0)));
            jTnome.setText(texto(jTbunidade.getValueAt(linha, 1)));
            jTendereco.setText(texto(jTbunidade.getValueAt(linha, 2)));
            jTtelefone.setText(texto(jTbunidade.getValueAt(linha, 3)));
            jThorario.setText(texto(jTbunidade.getValueAt(linha, 4)));
            jTdata.setText(texto(jTbunidade.getValueAt(linha, 5)));
            jTcusto.setText(texto(jTbunidade.getValueAt(linha, 6)));
        }
    }//GEN-LAST:event_jTbunidadeMouseClicked

    private void carregarTabela() {
        try {
            ControleUnidade cu = new ControleUnidade();
            DefaultTableModel modelo = (DefaultTableModel) jTbunidade.getModel();
            modelo.setRowCount(0); // Limpa a tabela antes de preencher de novo
            ArrayList<Unidade> unidades = cu.listar();
            for (int i = 0; i < unidades.size(); i++) {
                Unidade u = unidades.get(i);
                String data = "";
                if (u.getDataInauguracao() != null) {
                    data = u.getDataInauguracao().format(formato);
                }
                String custo = "";
                if (u.getCustoMensalOcupacao() != null) {
                    custo = u.getCustoMensalOcupacao().toString().replace(".", ",");
                }
                modelo.addRow(new Object[]{u.getUnidadeId(), u.getNome(), u.getEndereco(), u.getTelefone(), u.getHorarioFuncionamento(), data, custo});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao listar: " + e.getMessage());
        }
    }

    private void limpar() {
        jTcodigo.setText("");
        jTnome.setText("");
        jTendereco.setText("");
        jTtelefone.setText("");
        jThorario.setText("");
        jTdata.setText("");
        jTcusto.setText("");
        jTbunidade.clearSelection();
    }

    private String texto(Object valor) {
        if (valor == null) return "";
        return valor.toString();
    }

