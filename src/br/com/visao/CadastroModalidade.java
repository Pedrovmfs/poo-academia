    private void jBsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBsalvarActionPerformed
        // TODO add your handling code here:
        try {
            Modalidade m = new Modalidade();
            ControleModalidade cm = new ControleModalidade();
            m.setNome(jTnome.getText().trim());
            if (!jTcategoria.getText().trim().equals("")) {
                m.setCategoria(jTcategoria.getText().trim());
            }
            if (!jTambiente.getText().trim().equals("")) {
                m.setAmbienteNecessario(jTambiente.getText().trim());
            }
            if (!jTexperiencia.getText().trim().equals("")) {
                m.setExperienciaMinima(jTexperiencia.getText().trim());
            }
            if (!jTduracao.getText().trim().equals("")) {
                try {
                    m.setDuracaoLimite(Integer.valueOf(jTduracao.getText().trim()));
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Duração inválida! Digite só os minutos, ex: 60");
                    return;
                }
            }

            // codigo vazio -> inserir / preenchido -> alterar
            if (jTcodigo.getText().equals("")) {
                cm.inserir(m);
                JOptionPane.showMessageDialog(this, "Modalidade cadastrada com sucesso!");
            } else {
                m.setModalidadeId(Integer.valueOf(jTcodigo.getText()));
                cm.alterar(m);
                JOptionPane.showMessageDialog(this, "Modalidade alterada com sucesso!");
            }
            limpar();
            carregarTabela();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_jBsalvarActionPerformed

    private void jBexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBexcluirActionPerformed
        // TODO add your handling code here:
        if (jTcodigo.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Selecione uma modalidade na tabela!");
            return;
        }
        int resposta = JOptionPane.showConfirmDialog(this, "Deseja excluir esta modalidade?", "Excluir", JOptionPane.YES_NO_OPTION);
        if (resposta == JOptionPane.YES_OPTION) {
            try {
                Modalidade m = new Modalidade();
                ControleModalidade cm = new ControleModalidade();
                m.setModalidadeId(Integer.valueOf(jTcodigo.getText()));
                cm.deletar(m);
                JOptionPane.showMessageDialog(this, "Modalidade excluída com sucesso!");
                limpar();
                carregarTabela();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_jBexcluirActionPerformed

