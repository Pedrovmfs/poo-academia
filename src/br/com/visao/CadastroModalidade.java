    private void jTbmodalidadeMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTbmodalidadeMouseClicked
        // TODO add your handling code here:
        // joga os dados da linha selecionada nos campos
        int linha = jTbmodalidade.getSelectedRow();
        if (linha >= 0) {
            jTcodigo.setText(texto(jTbmodalidade.getValueAt(linha, 0)));
            jTnome.setText(texto(jTbmodalidade.getValueAt(linha, 1)));
            jTcategoria.setText(texto(jTbmodalidade.getValueAt(linha, 2)));
            jTambiente.setText(texto(jTbmodalidade.getValueAt(linha, 3)));
            jTexperiencia.setText(texto(jTbmodalidade.getValueAt(linha, 4)));
            jTduracao.setText(texto(jTbmodalidade.getValueAt(linha, 5)));
        }
    }//GEN-LAST:event_jTbmodalidadeMouseClicked

    private void carregarTabela() {
        try {
            ControleModalidade cm = new ControleModalidade();
            DefaultTableModel modelo = (DefaultTableModel) jTbmodalidade.getModel();
            modelo.setRowCount(0);
            ArrayList<Modalidade> modalidades = cm.listar();
            for (int i = 0; i < modalidades.size(); i++) {
                Modalidade m = modalidades.get(i);
                modelo.addRow(new Object[]{m.getModalidadeId(), m.getNome(), m.getCategoria(), m.getAmbienteNecessario(), m.getExperienciaMinima(), m.getDuracaoLimite()});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao listar: " + e.getMessage());
        }
    }

    private void limpar() {
        jTcodigo.setText("");
        jTnome.setText("");
        jTcategoria.setText("");
        jTambiente.setText("");
        jTexperiencia.setText("");
        jTduracao.setText("");
        jTbmodalidade.clearSelection();
    }

    private String texto(Object valor) {
        if (valor == null) {
            return "";
        }
        return valor.toString();
    }

