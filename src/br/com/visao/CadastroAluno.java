    private void jBsalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBsalvarActionPerformed
        // TODO add your handling code here:
        try {
            Aluno a = new Aluno();
            ControleAluno ca = new ControleAluno();
            a.setNome(jTnome.getText().trim());
            // tira pontos e traço do cpf, fica so os numeros
            a.setCpf(jTcpf.getText().replaceAll("\\D", ""));
            if (!jTnascimento.getText().trim().equals("")) {
                try {
                    a.setDataNascimento(LocalDate.parse(jTnascimento.getText().trim(), formato));
                } catch (Exception e) {
                    JOptionPane.showMessageDialog(this, "Data inválida! Use o formato dd/mm/aaaa");
                    return;
                }
            }
            if (!jTtelefone.getText().trim().equals("")) {
                a.setTelefone(jTtelefone.getText().trim());
            }
            if (!jTemail.getText().trim().equals("")) {
                a.setEmail(jTemail.getText().trim());
            }
            if (!jTendereco.getText().trim().equals("")) {
                a.setEndereco(jTendereco.getText().trim());
            }
            a.setStatus(jCbstatus.getSelectedItem().toString());

            // campo codigo vazio quer dizer aluno novo
            if (jTcodigo.getText().equals("")) {
                ca.inserir(a);
                JOptionPane.showMessageDialog(this, "Aluno cadastrado com sucesso!");
            } else {
                a.setPessoaId(Integer.valueOf(jTcodigo.getText()));
                ca.alterar(a);
                JOptionPane.showMessageDialog(this, "Aluno alterado com sucesso!");
            }
            limpar();
            carregarTabela();
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
        }
    }//GEN-LAST:event_jBsalvarActionPerformed

    private void jBexcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBexcluirActionPerformed
        // TODO add your handling code here:
        if (jTcodigo.getText().equals("")) {
            JOptionPane.showMessageDialog(this, "Selecione um aluno na tabela!");
            return;
        }
        int resposta = JOptionPane.showConfirmDialog(this, "Deseja excluir este aluno?", "Excluir", JOptionPane.YES_NO_OPTION);
        if (resposta == JOptionPane.YES_OPTION) {
            try {
                Aluno a = new Aluno();
                ControleAluno ca = new ControleAluno();
                a.setPessoaId(Integer.valueOf(jTcodigo.getText()));
                ca.deletar(a);
                JOptionPane.showMessageDialog(this, "Aluno excluído com sucesso!");
                limpar();
                carregarTabela();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Erro: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_jBexcluirActionPerformed

