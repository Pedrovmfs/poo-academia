    private void jTbalunoMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_jTbalunoMouseClicked
        // TODO add your handling code here:
        // linha selecionada -> campos
        int linha = jTbaluno.getSelectedRow();
        if (linha >= 0) {
            jTcodigo.setText(texto(jTbaluno.getValueAt(linha, 0)));
            jTnome.setText(texto(jTbaluno.getValueAt(linha, 1)));
            jTcpf.setText(texto(jTbaluno.getValueAt(linha, 2)));
            jTnascimento.setText(texto(jTbaluno.getValueAt(linha, 3)));
            jTtelefone.setText(texto(jTbaluno.getValueAt(linha, 4)));
            jTemail.setText(texto(jTbaluno.getValueAt(linha, 5)));
            jTendereco.setText(texto(jTbaluno.getValueAt(linha, 6)));
            jCbstatus.setSelectedItem(texto(jTbaluno.getValueAt(linha, 7)));
        }
    }//GEN-LAST:event_jTbalunoMouseClicked

    private void carregarTabela() {
        try {
            ControleAluno ca = new ControleAluno();
            DefaultTableModel modelo = (DefaultTableModel) jTbaluno.getModel();
            modelo.setRowCount(0);
            ArrayList<Aluno> alunos = ca.listar();
            for (int i = 0; i < alunos.size(); i++) {
                Aluno a = alunos.get(i);
                String nascimento = "";
                if (a.getDataNascimento() != null) {
                    nascimento = a.getDataNascimento().format(formato);
                }
                modelo.addRow(new Object[]{a.getPessoaId(), a.getNome(), a.getCpf(), nascimento, a.getTelefone(), a.getEmail(), a.getEndereco(), a.getStatus()});
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Erro ao listar: " + e.getMessage());
        }
    }

    private void limpar() {
        jTcodigo.setText("");
        jTnome.setText("");
        jTcpf.setText("");
        jTnascimento.setText("");
        jTtelefone.setText("");
        jTemail.setText("");
        jTendereco.setText("");
        jCbstatus.setSelectedIndex(0);
        jTbaluno.clearSelection();
    }

    private String texto(Object valor) {
        if (valor == null) {
            return "";
        }
        return valor.toString();
    }

