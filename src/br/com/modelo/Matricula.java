package br.com.modelo;

import java.time.LocalDate;

public class Matricula {
   private int matriculaId;
   private int alunoId;
   private int planoId;
   private int unidadeId;
   private LocalDate dataInicio;
   private LocalDate dataTermino;
   private String status;
   private String formaRenovacao;
   private String motivoCancelamento;
   private String canalMatricula;
   // nomes que vem do JOIN, so pra mostrar na tabela
   private String nomeAluno;
   private String nomePlano;
   private String nomeUnidade;

    public int getMatriculaId() {
        return matriculaId;
    }

    public void setMatriculaId(int matriculaId) {
        this.matriculaId = matriculaId;
    }

    public int getAlunoId() {
        return alunoId;
    }

    public void setAlunoId(int alunoId) {
        this.alunoId = alunoId;
    }

    public int getPlanoId() {
        return planoId;
    }

    public void setPlanoId(int planoId) {
        this.planoId = planoId;
    }

    public int getUnidadeId() {
        return unidadeId;
    }

    public void setUnidadeId(int unidadeId) {
        this.unidadeId = unidadeId;
    }

    public LocalDate getDataInicio() {
        return dataInicio;
    }

    public void setDataInicio(LocalDate dataInicio) {
        this.dataInicio = dataInicio;
    }

    public LocalDate getDataTermino() {
        return dataTermino;
    }

    public void setDataTermino(LocalDate dataTermino) {
        this.dataTermino = dataTermino;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getFormaRenovacao() {
        return formaRenovacao;
    }

    public void setFormaRenovacao(String formaRenovacao) {
        this.formaRenovacao = formaRenovacao;
    }

    public String getMotivoCancelamento() {
        return motivoCancelamento;
    }

    public void setMotivoCancelamento(String motivoCancelamento) {
        this.motivoCancelamento = motivoCancelamento;
    }

    public String getCanalMatricula() {
        return canalMatricula;
    }

    public void setCanalMatricula(String canalMatricula) {
        this.canalMatricula = canalMatricula;
    }

    public String getNomeAluno() {
        return nomeAluno;
    }

    public void setNomeAluno(String nomeAluno) {
        this.nomeAluno = nomeAluno;
    }

    public String getNomePlano() {
        return nomePlano;
    }

    public void setNomePlano(String nomePlano) {
        this.nomePlano = nomePlano;
    }

    public String getNomeUnidade() {
        return nomeUnidade;
    }

    public void setNomeUnidade(String nomeUnidade) {
        this.nomeUnidade = nomeUnidade;
    }

}
